CREATE TABLE inscripcion (
                             id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                             aspirante_id BIGINT NOT NULL REFERENCES aspirante(id),
                             numero_inscripcion VARCHAR(30) NOT NULL UNIQUE,
                             cumple_titulo_bachiller BOOLEAN NOT NULL,
                             cumple_icfes BOOLEAN NOT NULL,
                             tipo_documento VARCHAR(30) NOT NULL,
                             numero_documento VARCHAR(30) NOT NULL,
                             fecha_nacimiento DATE NOT NULL,
                             genero VARCHAR(30) NOT NULL,
                             telefono VARCHAR(30) NOT NULL,
                             ciudad_residencia VARCHAR(100) NOT NULL,
                             institucion_bachillerato VARCHAR(200) NOT NULL,
                             municipio_colegio VARCHAR(100) NOT NULL,
                             anio_graduacion INT NOT NULL,
                             codigo_resultado_icfes VARCHAR(50) NOT NULL,
                             puntaje_global_icfes INT NOT NULL,
                             facultad VARCHAR(150) NOT NULL,
                             programa VARCHAR(150) NOT NULL,
                             semestre VARCHAR(20) NOT NULL,
                             documento_identidad_url VARCHAR(500),
                             foto_url VARCHAR(500),
                             referencia_pago VARCHAR(100),
                             fecha_pago DATE,
                             banco_pago VARCHAR(100),
                             estado VARCHAR(30) NOT NULL DEFAULT 'EN_PROCESO',
                             fecha_creacion TIMESTAMP NOT NULL
);